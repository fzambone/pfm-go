// TestUsersMigration_CreatedAtImmutableOnUpdate verifies AC5: updating a row must not
// change created_at — only updated_at is allowed to change.
func TestUsersMigration_CreatedAtImmutableOnUpdate(t *testing.T) {
	ctx := context.Background()
	db := newTestDB(t, ctx)
	require.NoError(t, Migrate(ctx, db, usersMigrationsFS(t)))

	_, err := db.ExecContext(ctx,
		"INSERT INTO users (email, password_hash, display_name) VALUES ($1, $2, $3)",
		"eve@example.com", testPasswordHash, "Eve",
	)
	require.NoError(t, err)

	var createdBefore string
	err = db.QueryRowContext(ctx,
		"SELECT created_at::text FROM users WHERE email = $1",
		"eve@example.com",
	).Scan(&createdBefore)
	require.NoError(t, err)

	_, err = db.ExecContext(ctx,
		"UPDATE users SET display_name = $1, updated_at = NOW() WHERE email = $2",
		"Eve Updated", "eve@example.com",
	)
	require.NoError(t, err)

	var createdAfter string
	err = db.QueryRowContext(ctx,
		"SELECT created_at::text FROM users WHERE email = $1",
		"eve@example.com",
	).Scan(&createdAfter)
	require.NoError(t, err)

	assert.Equal(t, createdBefore, createdAfter, "created_at must not change on UPDATE")
}

