// TestUsersMigration_RollbackRemovesTable verifies AC7: running the Down migration
// drops the users table and all its indexes cleanly.
func TestUsersMigration_RollbackRemovesTable(t *testing.T) {
	ctx := context.Background()
	db := newTestDB(t, ctx)
	sub := usersMigrationsFS(t)

	require.NoError(t, Migrate(ctx, db, sub))

	var exists bool
	err := db.QueryRowContext(ctx,
		"SELECT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'users')",
	).Scan(&exists)
	require.NoError(t, err)
	require.True(t, exists, "users table must exist after Up")

	// Roll back all migrations using the goose Provider directly.
	provider, err := goose.NewProvider(goose.DialectPostgres, db, sub,
		goose.WithLogger(goose.NopLogger()),
	)
	require.NoError(t, err)

	_, err = provider.DownTo(ctx, 0)
	require.NoError(t, err)

	err = db.QueryRowContext(ctx,
		"SELECT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'users')",
	).Scan(&exists)
	require.NoError(t, err)
	assert.False(t, exists, "users table must be absent after rollback")
}
