// usersMigrationsFS returns the sub-filesystem used by the real application startup.
// It mirrors the fs.Sub call in cmd/pfm/main.go's run().
func usersMigrationsFS(t *testing.T) fs.FS {
	t.Helper()
	sub, err := fs.Sub(pfmdb.Migrations, "migrations")
	require.NoError(t, err)
	return sub
}

// testPasswordHash is a 128-character string satisfying the Argon2id minimum column width.
var testPasswordHash = strings.Repeat("x", 128)

// TestUsersMigration_UUIDGeneratedByDB verifies AC1: the database generates a UUIDv7
// when a user is inserted without an explicit id.
func TestUsersMigration_UUIDGeneratedByDB(t *testing.T) {
	ctx := context.Background()
	db := newTestDB(t, ctx)
	require.NoError(t, Migrate(ctx, db, usersMigrationsFS(t)))

	var id string
	err := db.QueryRowContext(ctx,
		"INSERT INTO users (email, password_hash, display_name) VALUES ($1, $2, $3) RETURNING id::text",
		"alice@example.com", testPasswordHash, "Alice",
	).Scan(&id)

	require.NoError(t, err)
	assert.NotEmpty(t, id, "id must be generated by the database")
	assert.Len(t, id, 36, "generated id must be a UUID (36 chars with dashes)")
}

// TestUsersMigration_EmailUniquenessEnforced verifies AC2: inserting two active users
// with the same email (case-insensitive) is rejected by the database.
func TestUsersMigration_EmailUniquenessEnforced(t *testing.T) {
	ctx := context.Background()
	db := newTestDB(t, ctx)
	require.NoError(t, Migrate(ctx, db, usersMigrationsFS(t)))

	_, err := db.ExecContext(ctx,
		"INSERT INTO users (email, password_hash, display_name) VALUES ($1, $2, $3)",
		"bob@example.com", testPasswordHash, "Bob",
	)
	require.NoError(t, err)

	// Same email with different case — must be rejected by the partial unique index.
	_, err = db.ExecContext(ctx,
		"INSERT INTO users (email, password_hash, display_name) VALUES ($1, $2, $3)",
		"BOB@example.com", testPasswordHash, "Bob Duplicate",
	)
	assert.Error(t, err, "duplicate email (case-insensitive) must be rejected")
}

// TestUsersMigration_SoftDeleteAllowsEmailReuse verifies AC3: after a user is soft-deleted,
// the same email can be registered again.
func TestUsersMigration_SoftDeleteAllowsEmailReuse(t *testing.T) {
	ctx := context.Background()
	db := newTestDB(t, ctx)
	require.NoError(t, Migrate(ctx, db, usersMigrationsFS(t)))

	_, err := db.ExecContext(ctx,
		"INSERT INTO users (email, password_hash, display_name) VALUES ($1, $2, $3)",
		"carol@example.com", testPasswordHash, "Carol",
	)
	require.NoError(t, err)

	// Soft-delete the user — partial index no longer covers this row.
	_, err = db.ExecContext(ctx,
		"UPDATE users SET deleted_at = NOW() WHERE email = $1",
		"carol@example.com",
	)
	require.NoError(t, err)

	// Re-registration with the same email must succeed.
	_, err = db.ExecContext(ctx,
		"INSERT INTO users (email, password_hash, display_name) VALUES ($1, $2, $3)",
		"carol@example.com", testPasswordHash, "Carol Re-registered",
	)
	assert.NoError(t, err, "email must be reusable after soft-delete")
}

